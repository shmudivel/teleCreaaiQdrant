from textwrap import dedent
from crewai import Task

class DzenTasks:
    """Tasks for creating Dzen.ru content."""
    
    def content_creation_task(self, agent, structure_part):
        return Task(
            description=dedent(f"""\
                Создание первой части статьи для dzen.ru, основываясь на оригинальном тексте:
                {structure_part}"""),
            expected_output=dedent(f"""\
                Первая часть статьи для dzen.ru, сохраняющая оригинальный тон, стиль и авторский голос:
                
                ВАЖНО:
                - Сохранить авторский стиль и тональность исходного текста
                - Уловить и воспроизвести "голос" автора, его особенности речи и выражения
                - Сохранить логику изложения и последовательность аргументов
                
                ТРЕБОВАНИЯ К ПЕРВОЙ ЧАСТИ:
                • Цепляющее начало, но в авторском стиле
                • Представление автора и его позиции
                • Заголовок-кликбейт, но соответствующий тону автора
                • Постановка проблемы и введение в тему
                
                СТРУКТУРА:
                • Эмоциональные первые 3 предложения 
                • Представление основной идеи
                • Плавные переходы между абзацами
                • Каждый абзац - одна законченная мысль
                
                УЧИТЫВАТЬ:
                • Не выдумывать факты и истории
                • Использовать только авторские примеры и данные
                • Писать от первого лица с соблюдением авторского стиля"""),
            agent=agent
        )
    
