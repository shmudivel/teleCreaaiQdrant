    def final_editing_task(self, agent, combined_content):
        return Task(
            description=dedent(f"""\
                Финальная редакция готового поста из 4 частей для dzen.ru, обеспечение стилистического и смыслового единства:
                
                {combined_content}"""),
            expected_output=dedent("""\
                Готовый пост для dzen.ru, сохраняющий целостный авторский голос и стиль:
                
                ОБЯЗАТЕЛЬНЫЕ КРИТЕРИИ КАЧЕСТВА:
                • Полная стилистическая и тональная согласованность всех частей
                • Единый авторский голос на протяжении всего текста
                • Логическая связность и последовательность между частями
                • Плавные, естественные переходы между всеми разделами
                • Сохранение уникальных авторских особенностей на протяжении всего текста
                • Целостное повествование, сохраняющее исходный посыл и ценность для читателя
                
                КОНЕЧНЫЙ РЕЗУЛЬТАТ:
                • Законченный материал, который читается как единое целое
                • Текст, который воспринимается как написанный одним человеком с единым стилем
                • Публикация, сохраняющая "душу" и особенности оригинального текста
                • Материал, который будет привлекательным для аудитории Дзен"""),
            agent=agent
        )

