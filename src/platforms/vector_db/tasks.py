from textwrap import dedent
from crewai import Task

class VectorDBTasks:
    """Tasks for getting answers directly from Sergey Chernenko via his knowledge base."""
    
    def research_task(self, agent, query):
        """Create a task for finding Sergey's thoughts on a specific query."""
        return Task(
            description=dedent(f"""\
                Найти, что думает Сергей Черненко по следующему вопросу:
                {query}
                
                Используй инструменты для поиска в интернете, чтобы найти:
                1. Прямые цитаты Сергея по этой теме
                2. Ключевые мнения и убеждения Сергея в этой области
                3. Примеры и метафоры, которые Сергей использовал для объяснения этой темы
                4. Связи этой темы с другими темами, которые затрагивал Сергей
                
                Важно найти не просто релевантную информацию, а именно то,
                что отражает личную позицию Сергея, его стиль мышления и его подход.
                
                ОГРАНИЧЕНИЯ ПО ПОИСКУ:
                1. Если в тексте выше предоставлен контекст из базы знаний, в первую очередь используй эту информацию
                2. Ограничься максимум 3 поисковыми запросами через exa_search
                3. Если после 3 запросов все еще недостаточно информации, работай с тем, что есть
                
                ИНСТРУКЦИИ ПО ИСПОЛЬЗОВАНИЮ ИНСТРУМЕНТОВ:
                КРАЙНЕ ВАЖНО: все инструменты требуют корректный формат запроса!
                
                ✓ ПРАВИЛЬНО:
                • exa_search: {{"query": "{query}"}}
                • exa_find_similar: {{"url": "URL для поиска похожих"}}
                • exa_get_contents: {{"ids": ["id1", "id2"]}}
                • exa_url_content: {{"url": "URL для получения содержимого"}}
                
                ✗ НЕПРАВИЛЬНО:
                {{}}
                {{"description": "{query}"}}
                "{query}"
                
                Поле query обязательно должно присутствовать и содержать непустую строку запроса.
                Без этого инструменты не будут работать правильно.
                """),
            expected_output=dedent("""\
                Результаты исследования мыслей и текстов Сергея Черненко, включающие:
                
                1. Прямые цитаты Сергея по заданной теме
                2. Основные идеи и убеждения Сергея в данной области
                3. Характерные примеры, метафоры и сравнения, которые использует Сергей
                4. Личное отношение Сергея к данному вопросу
                
                Информация должна быть организована так, чтобы максимально точно 
                представить мнение Сергея, сохраняя его стиль и подход к теме.
                """),
            agent=agent
        )
    
    def writing_task(self, agent, research_results, query):
        """Create a task for writing a response as if it comes directly from Sergey."""
        return Task(
            description=dedent(f"""\
                Ответить на вопрос пользователя так, как это сделал бы сам Сергей Черненко.
                
                Вопрос пользователя: {query}
                
                Результаты исследования текстов Сергея:
                {research_results}
                
                Создай ответ, который:
                1. Звучит так, как будто его пишет лично Сергей
                2. Сохраняет характерные особенности речи и стиля Сергея
                3. Отражает ключевые убеждения и позицию Сергея по данному вопросу
                4. Включает типичные для Сергея примеры, метафоры или истории
                5. Дает прямой и честный ответ в манере Сергея
                """),
            expected_output=dedent("""\
                Ответ от первого лица, как если бы его написал сам Сергей Черненко.
                
                Ответ должен:
                1. Быть написан от первого лица (я, мое мнение, мой опыт)
                2. Сохранять характерные речевые обороты Сергея
                3. Отражать его прямой и откровенный стиль общения
                4. Включать практические советы и рекомендации
                5. Содержать уникальные инсайты, основанные на опыте Сергея
                
                Финальный ответ должен звучать настолько аутентично, чтобы читатель 
                действительно поверил, что с ним общается сам Сергей Черненко.
                """),
            agent=agent
        )
    
    def fact_checking_task(self, agent, draft_response, query):
        """Create a task for ensuring the response accurately represents Sergey's voice and views."""
        return Task(
            description=dedent(f"""\
                Проверить, что ответ точно отражает то, что сказал бы Сергей Черненко по этому вопросу.
                
                Вопрос пользователя: {query}
                
                Черновик ответа от имени Сергея:
                {draft_response}
                
                Необходимо:
                1. Проверить, соответствует ли ответ взглядам и мнениям Сергея, выраженным в его текстах
                2. Убедиться, что стиль речи соответствует манере Сергея
                3. Проверить, не содержится ли в ответе мнений, которые противоречат позиции Сергея
                4. Оценить, насколько аутентично звучит ответ в целом
                
                При необходимости внести правки, чтобы ответ максимально точно 
                соответствовал тому, что сказал бы сам Сергей Черненко.
                """),
            expected_output=dedent("""\
                Отредактированный ответ от имени Сергея Черненко, который:
                
                1. Полностью соответствует взглядам и позиции Сергея
                2. Сохраняет его характерный стиль речи и манеру общения
                3. Включает типичные для Сергея выражения и обороты
                4. Звучит аутентично, как если бы был написан самим Сергеем
                
                В случае внесения правок, указать, что именно было изменено и почему
                эти изменения делают ответ более соответствующим тому, что сказал бы Сергей.
                """),
            agent=agent
        ) 