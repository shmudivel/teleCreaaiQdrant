from textwrap import dedent
from crewai import Task

class VCTasks:
    """Tasks for creating VC.ru content."""
    
    def content_creation_task(self, agent, structure_part):
        return Task(
            description=dedent(f"""\
                Создание первой части статьи для vc.ru, основываясь на оригинальном тексте:
                {structure_part}"""),
            expected_output=dedent(f"""\
                Первая часть статьи для vc.ru, сохраняющая оригинальный тон, стиль и авторский голос:
                
                ВАЖНО:
                - ВСЕГДА сохранять имя автора точно как оно указано в исходном тексте (Сергей Черненко)
                - НИКОГДА не использовать плейсхолдеры вроде "[Имя автора]"
                - Сохранить авторский стиль и тональность исходного текста
                - Уловить и воспроизвести "голос" автора, его особенности речи и выражения
                - Сохранить логику изложения и последовательность аргументов
                - НИКОГДА не выдумывать термины или концепции, которых нет в исходном тексте
                
                ТРЕБОВАНИЯ К ЯЗЫКУ:
                • Использовать естественный деловой русский язык без странных конструкций
                • Избегать чрезмерно формальных или академических оборотов
                • Не использовать запутанные термины без их объяснения
                
                ТРЕБОВАНИЯ К ПЕРВОЙ ЧАСТИ:
                • Цепляющее начало, но в авторском стиле
                • Представление автора (Сергей Черненко) и его позиции
                • Заголовок-кликбейт, но соответствующий тону автора
                • Постановка проблемы и введение в тему
                
                СТРУКТУРА:
                • Эмоциональные первые 3 предложения
                • Представление основной идеи
                • Плавные переходы между абзацами
                • Каждый абзац - одна законченная мысль
                • Избегать коротких абзацев из 1-2 предложений
                • Не использовать одиночные слова как предложения
                
                СТАТИСТИКА И ЦИФРЫ:
                • Представлять все числа и статистику точно как в оригинале
                • Объяснять значение цифр и их контекст
                • Сохранять точность финансовых показателей
                
                УЧИТЫВАТЬ:
                • Не выдумывать факты и истории
                • Использовать только авторские примеры и данные
                • Писать от первого лица с соблюдением авторского стиля"""),
            agent=agent
        )
    
