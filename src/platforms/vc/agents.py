from textwrap import dedent
from crewai import Agent
from src.vector_db_tool import VectorDBToolset

class VCAgents:
    """Agents for creating VKontakte content."""
    
    def content_creator_agent(self):
        vdb_tools = VectorDBToolset()
        return Agent(
            role="редактор контента для ВКонтакте",
            goal='редактировать только часть 1 из 4 частей контента',
            tools=vdb_tools.tools(),
            backstory=dedent("""\
                Я профессиональный редактор контента для ВКонтакте.

                Ваши задачи:
                • редактировать и четко придерживаться задания
                • создавать текст, адаптированный под аудиторию ВКонтакте
                • делать контент более молодежным и интерактивным
                 """),
            verbose=True
        )
    
